"""Regenerate responsive assets from retained originals (requires Pillow).

Output names include the content hash: /media/* can be cached immutably.
Run manually after replacing originals; normal builds use committed outputs.
"""
from hashlib import sha256
from io import BytesIO
from pathlib import Path
import json

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public"
OUTPUT = PUBLIC / "media"
OUTPUT.mkdir(exist_ok=True)
variants = {}


def encode(image, name, width, *, png=False):
    image = image.copy()
    image.thumbnail((width, round(width * image.height / image.width)), Image.Resampling.LANCZOS)
    buffer = BytesIO()
    if png:
        image.save(buffer, "PNG", optimize=True)
    else:
        image.save(buffer, "WEBP", quality=82, method=6)
    data = buffer.getvalue()
    extension = "png" if png else "webp"
    filename = f"{name}-{image.width}.{sha256(data).hexdigest()[:12]}.{extension}"
    (OUTPUT / filename).write_bytes(data)
    return {"src": f"/media/{filename}", "width": image.width, "height": image.height}


def responsive(source, widths, *, name=None, png=False):
    image = ImageOps.exif_transpose(Image.open(PUBLIC / source.lstrip("/")))
    images = [encode(image, name or Path(source).stem, width, png=png) for width in widths]
    variants[source] = {**images[-1], "srcSet": ", ".join(f"{item['src']} {item['width']}w" for item in images)}


responsive("/assets/hero.jpg", [960, 1280, 1920])
responsive("/assets/proizvodstvo-photo.jpg", [640, 1200])
responsive("/brand/mark-square.png", [36, 72], png=True)
for name in ["icons-process", "icons-industries"]:
    responsive(f"/assets/{name}.png", [1024])
for source in sorted((PUBLIC / "assets/industries").glob("*.jpg")):
    if not source.stem.endswith("-640"):
        responsive("/" + str(source.relative_to(PUBLIC)), [640, 1280], name="industry-" + source.stem)

# Match the centred crop of the existing cover image, using a portrait source
# rather than downloading the full landscape photo on narrow screens.
original = Image.open(PUBLIC / "assets/hero.jpg")
portrait = ImageOps.fit(original, (720, 1080), method=Image.Resampling.LANCZOS)
mobile = [encode(portrait, "hero-mobile", width) for width in [360, 720]]
variants["hero-mobile"] = {**mobile[-1], "srcSet": ", ".join(f"{item['src']} {item['width']}w" for item in mobile)}

manifest = "// Generated by scripts/optimize-images.py. Keep original assets as source files.\n"
manifest += "export type ImageVariant = { src: string; srcSet: string; width: number; height: number };\n"
manifest += "export const imageVariants: Record<string, ImageVariant | undefined> = "
manifest += json.dumps(variants, ensure_ascii=False, indent=2) + ";\n"
(ROOT / "src/data/images.ts").write_text(manifest)
print(f"Generated {len(variants)} image families. Optimized files: {sum(p.stat().st_size for p in OUTPUT.iterdir()):,} bytes.")
